class TestDataPoints:
    def _add_point(self, doc, series: str) -> None:
        points = find_child(_series(doc, series), "ChartDataPoints")
        vals = etree.SubElement(
            etree.SubElement(points, q("ChartDataPoint")), q("ChartDataPointValues")
        )
        etree.SubElement(vals, q("Y")).text = "=Sum(Fields!Amount.Value)"

    def test_extra_point(self, rich_path):
        _patch(rich_path, lambda d: self._add_point(d, "Quantity"))
        issues = _issues(rich_path)
        assert [(i["location"], i["message"]) for i in issues] == [
            (
                f"{CHART}>ChartSeries[Name='Quantity']>ChartDataPoints",
                "chart 'SalesByProduct': ChartSeries 'Quantity' has 2 ChartDataPoint(s) but "
                "the category hierarchy has 1 leaf member(s)",
            )
        ]

    def test_points_match_two_categories(self, rich_path):
        def two_categories(doc):
            members = find_child(find_child(_chart(doc), "ChartCategoryHierarchy"), "ChartMembers")
            m = etree.SubElement(members, q("ChartMember"))
            etree.SubElement(m, q("Label")).text = "Other"
            for name in ("Amount", "Quantity", "Total"):
                self._add_point(doc, name)

        _patch(rich_path, two_categories)
        assert _issues(rich_path) == []

    def test_no_category_members_counts_as_one(self, rich_path):
        def strip(doc):
            hierarchy = find_child(_chart(doc), "ChartCategoryHierarchy")
            hierarchy.remove(find_child(hierarchy, "ChartMembers"))

        _patch(rich_path, strip)
        assert _issues(rich_path) == []
        _patch(rich_path, lambda d: self._add_point(d, "Total"))
        assert _messages(rich_path) == [
            "chart 'SalesByProduct': ChartSeries 'Total' has 2 ChartDataPoint(s) but "
            "ChartCategoryHierarchy has no ChartMember (which counts as 1)"
        ]


# ---- ChartAreaName / ValueAxisName / CategoryAxisName ----------------------


def _add_area(doc, name: str, value_axis: str, category_axis: str) -> None:
    areas = find_child(_chart(doc), "ChartAreas")
    area = etree.SubElement(areas, q("ChartArea"), Name=name)
    etree.SubElement(
        etree.SubElement(area, q("ChartCategoryAxes")), q("ChartAxis"), Name=category_axis
    )
    etree.SubElement(etree.SubElement(area, q("ChartValueAxes")), q("ChartAxis"), Name=value_axis)


class TestAreasAndAxes:
    def test_dangling_area(self, rich_path):
        _patch(rich_path, lambda d: _set(_series(d, "Amount"), "ChartAreaName", "Nope"))
        issues = _issues(rich_path)
        assert [(i["location"], i["message"]) for i in issues] == [
            (
                f"{CHART}>ChartSeries[Name='Amount']>ChartAreaName",
                "chart 'SalesByProduct': series 'Amount' has ChartAreaName 'Nope' but the "
                "chart's ChartAreas are ['Default']",
            )
        ]

    def test_existing_area_is_clean(self, rich_path):
        _patch(rich_path, lambda d: _set(_series(d, "Amount"), "ChartAreaName", "Default"))
        assert _issues(rich_path) == []

    @pytest.mark.parametrize("local", ["ValueAxisName", "CategoryAxisName"])
    def test_dangling_axis(self, rich_path, local):
        _patch(rich_path, lambda d: _set(_series(d, "Total"), local, "Secondary"))
        issues = _issues(rich_path)
        assert [i["location"] for i in issues] == [f"{CHART}>ChartSeries[Name='Total']>{local}"]
        assert f"has {local} 'Secondary' but ChartArea 'Default' has" in issues[0]["message"]

    @pytest.mark.parametrize("local", ["ValueAxisName", "CategoryAxisName"])
    def test_existing_axis_is_clean(self, rich_path, local):
        _patch(rich_path, lambda d: _set(_series(d, "Total"), local, "Primary"))
        assert _issues(rich_path) == []

    def test_axis_resolves_in_the_series_area(self, rich_path):
        def second_area(doc):
            _add_area(doc, "Second", "SecondValue", "SecondCategory")
            s = _series(doc, "Total")
            _set(s, "ChartAreaName", "Second")
            _set(s, "ValueAxisName", "SecondValue")
            _set(s, "CategoryAxisName", "SecondCategory")
            # Without ChartAreaName the first area's axes apply.
            _set(_series(doc, "Amount"), "ValueAxisName", "SecondValue")

        _patch(rich_path, second_area)
        assert [i["location"] for i in _issues(rich_path)] == [
            f"{CHART}>ChartSeries[Name='Amount']>ValueAxisName"
        ]

    def test_axis_check_skipped_when_area_dangles(self, rich_path):
        def corrupt(doc):
            _set(_series(doc, "Total"), "ChartAreaName", "Nope")
            _set(_series(doc, "Total"), "ValueAxisName", "Primary")

        _patch(rich_path, corrupt)
        assert [i["location"].rsplit(">", 1)[1] for i in _issues(rich_path)] == ["ChartAreaName"]


