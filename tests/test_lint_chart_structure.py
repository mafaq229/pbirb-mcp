def test_well_built_chart_with_derived_series_is_clean(tmp_path):
    path = tmp_path / "report.rdl"
    shutil.copy(MINIMAL, path)
    insert_chart_from_template(
        str(path), "C", "MainDataset", "ProductName", "Amount", "3in", "0in", "5in", "3in"
    )
    add_chart_series(str(path), "C", "Qty", "ProductID", "Line")

    def derive(doc):
        chart = _chart(doc, "C")
        _add_derived(chart, "AmountMA", "Amount")
        for s in chart_shape.series_list(chart):
            _set(s, "LegendName", "Default")
            _set(s, "ChartAreaName", "Default")
            _set(s, "ValueAxisName", "Primary")
            _set(s, "CategoryAxisName", "Primary")

    _patch(path, derive)
    chart = _chart(RDLDocument.open(path), "C")
    assert len(chart_shape.series_list(chart)) == 2
    assert len(chart_shape.series_leaf_members(chart)) == 2
    assert _issues(path) == []
    assert validate_report(str(path))["valid"]
    assert [i for i in lint_report(str(path))["issues"] if i["severity"] == "error"] == []


def test_issue_repro_structure_half(rich_path):
    """The repro's chart-structure findings: Type 'Pie' and 4 series vs 1
    member (the tools no longer produce either, so the file is patched)."""
    add_chart_series(str(rich_path), "SalesByProduct", "Ghost", "Amount")

    def corrupt(doc):
        _set(_series(doc, "Ghost"), "Type", "Pie")
        find_child(_series(doc, "Ghost"), "Subtype").getparent().remove(
            find_child(_series(doc, "Ghost"), "Subtype")
        )
        members = _series_members(doc)
        for m in find_children(members, "ChartMember")[1:]:
            members.remove(m)

    _patch(rich_path, corrupt)
    assert validate_report(str(rich_path))["valid"]  # the XSD sees none of it
    msgs = _messages(rich_path)
    assert "chart 'SalesByProduct': 4 ChartSeries but 1 leaf ChartMember(s) in " in msgs[0]
    assert any("Type 'Pie' is not an RDL ChartSeries Type" in m for m in msgs)
    assert any("Type=Shape, Subtype=Pie" in m for m in msgs)
    verify = verify_report(str(rich_path))
    assert verify["valid"] is False
    assert RULE in {i["rule"] for i in verify["issues"]}


# ---- series vs series-hierarchy leaves ------------------------------------


class TestSeriesMembers:
    def test_more_series_than_members(self, rich_path):
        _patch(
            rich_path,
            lambda d: _series_members(d).remove(
                find_children(_series_members(d), "ChartMember")[2]
            ),
        )
        issues = _issues(rich_path)
        assert [(i["location"], i["message"]) for i in issues] == [
            (
                f"{CHART}>ChartSeriesHierarchy",
                "chart 'SalesByProduct': 3 ChartSeries but 2 leaf ChartMember(s) in "
                "ChartSeriesHierarchy",
            )
        ]

    def test_more_members_than_series(self, rich_path):
        def corrupt(doc):
            m = etree.SubElement(_series_members(doc), q("ChartMember"))
            etree.SubElement(m, q("Label")).text = "Stale"

        _patch(rich_path, corrupt)
        assert "3 ChartSeries but 4 leaf ChartMember(s)" in _messages(rich_path)[0]

    def test_nested_members_count_leaves(self, rich_path):
        # Grouping the three static members under one dynamic member keeps
        # three leaves.
        def nest(doc):
            members = _series_members(doc)
            outer = etree.Element(q("ChartMember"))
            etree.SubElement(outer, q("Group"), Name="SeriesGroup")
            inner = etree.SubElement(outer, q("ChartMembers"))
            for m in find_children(members, "ChartMember"):
                inner.append(m)
            etree.SubElement(outer, q("Label")).text = "=Fields!ProductName.Value"
            members.append(outer)

        _patch(rich_path, nest)
        assert _issues(rich_path) == []

    def test_no_members_counts_as_one(self, rich_path):
        def strip(doc):
            chart = _chart(doc)
            hierarchy = find_child(chart, "ChartSeriesHierarchy")
            hierarchy.remove(find_child(hierarchy, "ChartMembers"))
            coll = find_child(find_child(chart, "ChartData"), "ChartSeriesCollection")
            for s in find_children(coll, "ChartSeries")[1:]:
                coll.remove(s)

        _patch(rich_path, strip)
        assert _issues(rich_path) == []
        # hierarchy_problems itself keeps counting an empty hierarchy as 0.
        chart = _chart(RDLDocument.open(rich_path))
        assert chart_shape.hierarchy_problems(chart) == [
            "1 ChartSeries but 0 leaf ChartMember(s) in ChartSeriesHierarchy"
        ]

    def test_no_members_with_several_series(self, rich_path):
        def strip(doc):
            hierarchy = find_child(_chart(doc), "ChartSeriesHierarchy")
            hierarchy.remove(find_child(hierarchy, "ChartMembers"))

        _patch(rich_path, strip)
        assert _messages(rich_path) == [
            "chart 'SalesByProduct': 3 ChartSeries but ChartSeriesHierarchy has no "
            "ChartMember (which counts as 1)"
        ]


