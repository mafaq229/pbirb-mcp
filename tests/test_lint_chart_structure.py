# ---- helpers ---------------------------------------------------------------


def _chart(doc: RDLDocument, name: str = "SalesByProduct") -> etree._Element:
    return doc.root.find(f".//{{{RDL_NS}}}Chart[@Name='{name}']")


def _series(doc: RDLDocument, name: str) -> etree._Element:
    return doc.root.find(f".//{{{RDL_NS}}}ChartSeries[@Name='{name}']")


def _set(parent: etree._Element, local: str, text: str) -> etree._Element:
    node = find_child(parent, local)
    if node is None:
        node = etree.SubElement(parent, q(local))
    node.text = text
    return node


def _patch(path: Path, fn) -> None:
    doc = RDLDocument.open(path)
    fn(doc)
    doc.save()


def _issues(path: Path) -> list[dict]:
    return lint_report(str(path), [RULE])["issues"]


def _messages(path: Path) -> list[str]:
    return [i["message"] for i in _issues(path)]


def _add_derived(chart: etree._Element, name: str, source: str) -> etree._Element:
    data = find_child(chart, "ChartData")
    coll = find_child(data, "ChartDerivedSeriesCollection")
    if coll is None:
        coll = etree.SubElement(data, q("ChartDerivedSeriesCollection"))
    d = etree.SubElement(coll, q("ChartDerivedSeries"))
    inner = etree.SubElement(d, q("ChartSeries"), Name=name)
    etree.SubElement(inner, q("Type")).text = "Line"
    etree.SubElement(d, q("SourceChartSeriesName")).text = source
    etree.SubElement(d, q("DerivedSeriesFormula")).text = "MovingAverage"
    return d


def _series_members(doc: RDLDocument) -> etree._Element:
    return chart_shape.series_hierarchy_members(_chart(doc))


