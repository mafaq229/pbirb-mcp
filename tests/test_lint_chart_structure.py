# ---- Type / Subtype --------------------------------------------------------


class TestSeriesType:
    @pytest.mark.parametrize(
        "type_text, subtype_text, fragment",
        [
            ("Pie", None, "Type 'Pie' is not an RDL ChartSeries Type"),
            ("Bogus", "Plain", "Type 'Bogus' is not an RDL ChartSeries Type"),
            ("Column", "Pie", "Subtype 'Pie' is not valid for Type 'Column'"),
            ("Line", "Stacked", "Subtype 'Stacked' is not valid for Type 'Line'"),
        ],
    )
    def test_invalid(self, rich_path, type_text, subtype_text, fragment):
        def corrupt(doc):
            s = _series(doc, "Amount")
            _set(s, "Type", type_text)
            sub = find_child(s, "Subtype")
            if subtype_text is None:
                s.remove(sub)
            else:
                sub.text = subtype_text

        _patch(rich_path, corrupt)
        issues = _issues(rich_path)
        assert [i["location"] for i in issues] == [f"{CHART}>ChartSeries[Name='Amount']>Type"]
        assert fragment in issues[0]["message"]

    @pytest.mark.parametrize(
        "type_text, subtype_text",
        [("Shape", "Pie"), ("Range", "Candlestick"), ("Polar", "Radar"), (None, None)],
    )
    def test_valid(self, rich_path, type_text, subtype_text):
        def write(doc):
            s = _series(doc, "Amount")
            for local, text in (("Type", type_text), ("Subtype", subtype_text)):
                if text is None:
                    s.remove(find_child(s, local))
                else:
                    _set(s, local, text)

        _patch(rich_path, write)
        assert _issues(rich_path) == []


