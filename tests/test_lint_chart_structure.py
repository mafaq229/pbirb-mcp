"""Tests for the ``chart-structure`` lint rule (#45, items 3-4).

Each invariant has a positive (fires) and a negative (stays quiet) case.
Broken charts are made by patching ``pbi_chart_rich.rdl`` (chart
``SalesByProduct``: series Amount / Quantity / Total, three series
members, one category member, area ``Default`` with ``Primary`` axes,
legend ``Default``, palette EarthTones) in-test.

The expression half of #45 (chart point values in
``missing-field-reference``, dataset-scoped ``field-out-of-scope``) lands
with #46 and is not tested here.
"""

